/**
 * Find a preset by its identifier.
 *
 * @param id - identifier such as "e23-1-1".
 * @returns the preset, or undefined when no preset has that id.
 */
export function findPreset(id: string): CurvePreset | undefined {
  return CURVE_PRESETS.find((preset) => preset.id === id);
}
