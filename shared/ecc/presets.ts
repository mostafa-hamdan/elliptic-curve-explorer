/**
 * Ready-made curves: small textbook curves that can be checked by hand, and two real
 * curves used on the internet today. Each comes with a sample point (and a second point
 * and a scalar) so one click sets up a complete example.
 */

/** A ready-made example. Numbers are kept as text so they can fill input boxes directly. */
export interface CurvePreset {
  /** Stable identifier used in menus and tests. */
  id: string;
  /** Name shown in the menu. */
  label: string;
  /** 'textbook' curves are small enough to list; 'real' curves are 256-bit. */
  group: 'textbook' | 'real';
  /** One line about where the curve comes from. */
  note: string;
  p: string;
  a: string;
  b: string;
  /** Sample point P as [x, y]. */
  pointP: readonly [string, string];
  /** Second sample point Q as [x, y]. */
  pointQ: readonly [string, string];
  /** Sample scalar k for kP. */
  k: string;
}

